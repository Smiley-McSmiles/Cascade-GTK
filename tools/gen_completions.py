#!/usr/bin/env python3
"""Generate bash, zsh and fish completions for `cascade` from its real argument parser.

    python3 tools/gen_completions.py           # write data/completions/{cascade.bash,_cascade,cascade.fish}
    python3 tools/gen_completions.py --check   # fail when the committed files are out of date (CI)
"""
import argparse
import os
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
sys.path.insert(0, ROOT)

from cascade import cli, schema  # noqa: E402

OUT = os.path.join(ROOT, "data", "completions")


def model():
    parser = cli.build_parser()
    sub = next(a for a in parser._actions if isinstance(a, argparse._SubParsersAction))
    globals_ = sorted(o for a in parser._actions for o in a.option_strings if o.startswith("--"))
    cmds = {}
    helps = {a.dest: a.help or "" for a in sub._choices_actions}
    seen = set()
    for name, p in sub.choices.items():
        if id(p) in seen and name not in helps:
            continue            # aliases share the parser of their command
        seen.add(id(p))
        opts, choices = [], {}
        for a in p._actions:
            if a.help == argparse.SUPPRESS:
                continue
            opts += [o for o in a.option_strings if o.startswith("--")]
            if a.choices and not a.option_strings:
                choices["positional"] = list(a.choices)
            elif a.choices:
                for o in a.option_strings:
                    choices[o] = list(a.choices)
        cmds[name] = {"help": helps.get(name, ""), "opts": sorted(set(opts) - {"--help"}), "choices": choices}
    return globals_, cmds


def bash(globals_, cmds):
    keys = " ".join(sorted(schema.SPECS))
    lines = ["# bash completion for cascade (generated by tools/gen_completions.py)", "_cascade() {",
             "    local cur prev words cword",
             "    _init_completion 2>/dev/null || { cur=${COMP_WORDS[COMP_CWORD]}; prev=${COMP_WORDS[COMP_CWORD-1]}; "
             "words=(\"${COMP_WORDS[@]}\"); cword=$COMP_CWORD; }",
             "    local cmd= i",
             "    for ((i=1; i < cword; i++)); do case ${words[i]} in -*) ;; *) cmd=${words[i]}; break ;; esac; done",
             "    if [[ -z $cmd ]]; then",
             "        COMPREPLY=($(compgen -W \"%s %s\" -- \"$cur\"))" % (" ".join(sorted(cmds)), " ".join(globals_)),
             "        return",
             "    fi",
             "    case $cmd in"]
    for name, c in sorted(cmds.items()):
        words = list(c["opts"]) + c["choices"].get("positional", [])
        if name in ("get", "set", "config"):
            words.append(keys)
        files = name in ("add", "create", "gui", "move")
        body = "COMPREPLY=($(compgen -W \"%s\" -- \"$cur\"))" % " ".join(words)
        if files:
            body += "; [[ $cur != -* ]] && COMPREPLY+=($(compgen -f -- \"$cur\"))"
        lines.append("        %s) %s ;;" % (name, body))
    lines += ["    esac", "}", "complete -F _cascade cascade", ""]
    return "\n".join(lines)


def zsh(globals_, cmds):
    lines = ["#compdef cascade", "# zsh completion for cascade (generated by tools/gen_completions.py)", "",
             "_cascade() {", "    local -a commands", "    commands=("]
    for name, c in sorted(cmds.items()):
        lines.append("        '%s:%s'" % (name, c["help"].replace("'", "").replace(":", " -")))
    lines += ["    )", "    if (( CURRENT == 2 )); then", "        _describe -t commands 'cascade command' commands",
              "        _arguments '*:: :->none' %s" % " ".join("'%s[option]'" % g for g in globals_),
              "        return", "    fi", "    case $words[2] in"]
    keys = " ".join(sorted(schema.SPECS))
    for name, c in sorted(cmds.items()):
        extra = c["choices"].get("positional", [])
        if name in ("get", "set", "config"):
            extra = keys.split()
        files = name in ("add", "create", "gui", "move")
        vals = " ".join(c["opts"] + extra)
        if files and vals:
            action = "_alternative 'opts:option:(%s)' 'files:file:_files'" % vals
        elif files:
            action = "_files"
        elif vals:
            action = "compadd -- %s" % vals
        else:
            action = ":"
        lines.append("        %s) %s ;;" % (name, action))
    lines += ["    esac", "}", "", "_cascade \"$@\"", ""]
    return "\n".join(lines)


def fish(globals_, cmds):
    lines = ["# fish completion for cascade (generated by tools/gen_completions.py)",
             "set -l cascade_cmds %s" % " ".join(sorted(cmds)),
             "complete -c cascade -f"]
    for g in globals_:
        lines.append("complete -c cascade -n 'not __fish_seen_subcommand_from $cascade_cmds' -l %s" % g[2:])
    for name, c in sorted(cmds.items()):
        lines.append("complete -c cascade -n 'not __fish_seen_subcommand_from $cascade_cmds' -a %s -d '%s'"
                     % (name, c["help"].replace("'", "")))
        for o in c["opts"]:
            lines.append("complete -c cascade -n '__fish_seen_subcommand_from %s' -l %s" % (name, o[2:]))
        if c["choices"].get("positional"):
            lines.append("complete -c cascade -n '__fish_seen_subcommand_from %s' -a '%s'"
                         % (name, " ".join(c["choices"]["positional"])))
        if name in ("get", "set", "config"):
            lines.append("complete -c cascade -n '__fish_seen_subcommand_from %s' -a '%s'"
                         % (name, " ".join(sorted(schema.SPECS))))
        if name in ("add", "create", "gui", "move"):
            lines.append("complete -c cascade -n '__fish_seen_subcommand_from %s' -F" % name)
    return "\n".join(lines) + "\n"


def main():
    globals_, cmds = model()
    files = {"cascade.bash": bash(globals_, cmds), "_cascade": zsh(globals_, cmds),
             "cascade.fish": fish(globals_, cmds)}
    if "--check" in sys.argv:
        stale = []
        for name, text in files.items():
            try:
                with open(os.path.join(OUT, name), encoding="utf-8") as fh:
                    if fh.read() != text:
                        stale.append(name)
            except OSError:
                stale.append(name)
        if stale:
            print("out of date: %s (run python3 tools/gen_completions.py)" % ", ".join(stale), file=sys.stderr)
            return 1
        print("completions are up to date")
        return 0
    os.makedirs(OUT, exist_ok=True)
    for name, text in files.items():
        with open(os.path.join(OUT, name), "w", encoding="utf-8") as fh:
            fh.write(text)
    print("wrote %s" % ", ".join(sorted(files)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
